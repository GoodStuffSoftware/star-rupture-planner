// Generator of src/data/versions.ts. Shared by scripts/refresh-data.mjs (upstream refresh) and
// scripts/publish-game-data.mjs (our own pipeline), so both always write the same file.
import { sortVersions, pickDefaultVersion } from './versionLogic.mjs'

export function humanLabel(dirName) {
  // Known labels for exact matches
  const known = {
    playtest: 'Playtest',
    earlyaccess: 'Early Access',
  }
  if (known[dirName]) return known[dirName]

  // Split on underscores, then insert spaces between letters and digits within tokens
  return dirName
    .split('_')
    .map((tok) =>
      tok
        // "update1" → "update 1"
        .replace(/([a-zA-Z])(\d)/g, '$1 $2')
        .split(' ')
        .map((w) => {
          const upper = w.toUpperCase()
          if (upper === 'PTB' || upper === 'QOL') return upper === 'QOL' ? 'QoL' : 'PTB'
          return w.charAt(0).toUpperCase() + w.slice(1)
        })
        .join(' '),
    )
    .join(' ')
}

/** The full text of src/data/versions.ts for these version folder ids (any order in, chronological out). */
export function renderVersionsTs(ids) {
  // Chronological order (see scripts/lib/versionLogic.mjs); the selector reverses it for display.
  const sorted = sortVersions(ids)
  const versionInfos = sorted.map((v) => ({ id: v, label: humanLabel(v) }))
  // Default = newest NON-test version, so a PTB is listed but never auto-selected.
  const defaultVersion = pickDefaultVersion(versionInfos)
  const text = `// AUTO-GENERATED by scripts/refresh-data.mjs — do not edit manually.
// Re-run \`npm run refresh-data\` to update when a new game version drops.

export interface VersionInfo {
  id: string
  label: string
}

export const VERSIONS: VersionInfo[] = [
${sorted.map((v) => `  { id: '${v}', label: '${humanLabel(v)}' },`).join('\n')}
]

export const DEFAULT_VERSION = '${defaultVersion}'
`
  return { text, versions: sorted, defaultVersion }
}
